-- Опечатка импорта: у договора 305 в названии заказчика потерялась
-- закрывающая кавычка — «ООО "Велесстрой» вместо «ООО "Велесстрой"».
-- У остальных четырёх договоров того же заказчика кавычка на месте.
--
-- Видно это стало в отчётах ИД и КС: там подпись карточки собирается из
-- внутреннего номера и заказчика («305 · ООО "Велесстрой»), и оборванная
-- кавычка читается как обрезанный текст.
--
-- Правка точечная и идемпотентная: условие включает и номер договора, и
-- прежнее значение, поэтому повторный прогон миграций ничего не тронет, а
-- уже исправленное вручную имя не будет перезаписано.
UPDATE erp_contracts
SET customer = 'ООО "Велесстрой"'
WHERE internal_number = '305' AND customer = 'ООО "Велесстрой';
